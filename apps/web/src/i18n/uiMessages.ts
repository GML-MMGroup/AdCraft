export type UiMessageKey = keyof typeof uiMessages;
export type MessageValues = Readonly<Record<string, string | number>>;

export function translateUi(locale: string, key: UiMessageKey, values: MessageValues = {}): string {
  const message = locale.toLowerCase().startsWith("zh") ? (uiMessages[key] ?? key) : key;
  return message.replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder));
}
